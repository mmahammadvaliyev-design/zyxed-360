// Общая форма данных тура. Ей же описывается data.json в экспортированном туре —
// значит и приложение, и автономный плеер понимают один и тот же формат.

// Вложение к заметке («Богатые заметки»): любой файл — PDF, DWG, 3D-модель…
// (см. engine/files.ts). Как и фото: в БД — Blob (data), в экспортированном
// манифесте — data: URI (url); оба поля вместе не бывают. Тип называется
// NotePdf и поле Hotspot.pdfs исторически — по смыслу это «вложения».
export interface NotePdf {
  name: string; // имя файла, под которым он скачивается
  data?: Blob;
  url?: string;
  // Вместо файла — ссылка (например, на модель Navisworks в Autodesk Viewer):
  // тогда data/url нет, на карточке кнопка «Открыть».
  href?: string;
}

export interface Hotspot {
  id: string;
  yaw: number; // радианы
  pitch: number; // радианы
  label: string;
  targetId: string | null; // id сцены, куда переходим (null — просто подпись)
  // Функция «Богатые заметки»: развёрнутое описание info-точки (без targetId).
  note?: string;
  // «Скрытый переход»: маркер не виден зрителю (кликабельная зона остаётся) —
  // чтобы сфера не загораживала картинку. Только для переходов (targetId).
  hidden?: boolean;
  // Фото крупным планом — храним как Blob в БД (photo) во время редактирования;
  // в экспортированном манифесте вместо него — data: URI (photoUrl), как и
  // с картинками сцен. Оба поля не встречаются вместе на одном объекте.
  photo?: Blob;
  photoUrl?: string;
  pdfs?: NotePdf[];
}

// Функция «Линии» (хайлайтер, см. engine/lines.ts). Линия — объект всего
// тура; штрихи лежат на панорамах.
export interface LineDef {
  id: string;
  name: string;
  color: string; // #rrggbb
  // «Невидимая» линия: на панораме не рисуется, но зона остаётся кликабельной
  // (и перечислена в легенде) — клик по трубе открывает документацию.
  hidden?: boolean;
  // Толщина линии в градусах обзора (по умолчанию 2.5°): и ширина маркера, и
  // ширина кликабельной зоны — чтобы линия «накрывала» трубу целиком.
  width?: number;
  // «Сужение к концу»: каждый штрих линии сужается от начала (там, где вы
  // начали рисовать) к концу — для труб, уходящих вдаль. Конец = 30% начала.
  taper?: boolean;
  // Документация линии — то же содержимое, что у заметки: текст, фото,
  // вложения (PDF/DWG/3D-модели) и ссылки. Клик по любому штриху линии на
  // любой панораме открывает карточку с этим содержимым. photo — Blob в БД,
  // photoUrl — data: URI в манифесте экспорта (как у Hotspot).
  note?: string;
  photo?: Blob;
  photoUrl?: string;
  pdfs?: NotePdf[];
}
export interface LinePoint {
  yaw: number; // радианы
  pitch: number;
}
export interface Stroke {
  id: string;
  lineId: string;
  points: LinePoint[];
  // Штрих «по точкам»: рисовать плавной кривой через вершины (а не ломаной).
  smooth?: boolean;
}

export interface SceneMeta {
  id: string;
  title: string;
  // Функция «Линии»: штрихи линий на этой панораме.
  strokes?: Stroke[];
  // Толщина линий именно НА ЭТОЙ панораме (градусы обзора): одна и та же труба
  // на разных сканах — на разном расстоянии. Нет значения — берётся общая
  // толщина линии (LineDef.width) или 2.5° по умолчанию.
  lineWidths?: Record<string, number>;
  width: number;
  height: number;
  order: number;
  yaw: number; // стартовый вид
  pitch: number;
  fov: number;
  hotspots: Hotspot[];
  // Функция «Карта тура»: положение точки съёмки на плане объекта (проценты
  // от размера картинки плана, 0–100). Не задано — точка ещё не расставлена
  // вручную, показывается в служебной позиции по умолчанию.
  mapX?: number;
  mapY?: number;
}

// Манифест экспортированного тура. Встраивается прямо в index.html плеера
// (id="tour-data"), картинки — как data: URI в images[sceneId]: так пакет
// открывается и двойным кликом с диска (браузеры блокируют fetch() локальных
// файлов по file://), и с любого статического хостинга — без отдельного
// запроса data.json/картинок.
export interface TourManifest {
  title: string;
  scenes: SceneMeta[];
  images: Record<string, string>;
  // Снимок состояния переключаемых функций на момент экспорта (см. src/features.ts) —
  // плеер должен вести себя так же, как приложение вело себя при публикации.
  features?: Record<string, boolean>;
  // Функция «Брендинг тура» (src/branding.ts) — логотип (data: URI) и подпись
  // в углу плеера. Присутствует, только если функция была включена при экспорте.
  branding?: { logo?: string; text?: string };
  // Язык приложения на момент экспорта (src/appLanguage.ts) — на нём плеер
  // показывает свои кнопки/подписи. Содержимое тура (названия, заметки) не
  // переводится — оно показывается ровно так, как его ввёл автор.
  lang?: "ru" | "en";
  // Функция «Карта тура»: план объекта (data: URI, как и картинки сцен) —
  // присутствует, только если функция была включена при экспорте и план
  // загружен. Положения точек — в scenes[].mapX/mapY.
  mapImage?: string;
  // Функция «Линии»: список линий тура (штрихи — в scenes[].strokes).
  lines?: LineDef[];
}
