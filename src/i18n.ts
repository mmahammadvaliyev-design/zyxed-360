// Перевод интерфейса приложения (кнопки/подписи/сообщения) — отдельно от
// содержимого тура: названия панорам и заметки пользователь вводит сам, и они
// не переводятся. Язык общий, appLanguage.ts.
// Без отдельного словаря ключей — русский и английский вариант пишутся
// рядом прямо в месте использования (t("Текст", "Text")), как в остальном
// коде этого проекта: меньше риска разъехаться/забыть ключ при правках.
import { getAppLanguage, useAppLanguage } from "./appLanguage";

export function useT(): (ru: string, en: string) => string {
  const lang = useAppLanguage();
  return (ru: string, en: string) => (lang === "en" ? en : ru);
}

// Вне React-компонентов (обработчики ошибок, хелперы) — читает язык на
// момент вызова, без подписки на изменения (там и не нужно: строка
// формируется заново при каждом вызове).
export function tNow(ru: string, en: string): string {
  return getAppLanguage() === "en" ? en : ru;
}
